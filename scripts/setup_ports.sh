# Bind A1Z-T Leader serial adapters and A1Z follower CAN adapters by USB serial.
# Example (dual arm):
# LEADER_LEFT_SERIAL=... LEADER_RIGHT_SERIAL=... \
# CAN_LEFT_SERIAL=... CAN_RIGHT_SERIAL=... bash scripts/setup_ports.sh
# Use --list to inspect currently connected adapter serials first.
set -Eeuo pipefail

list_adapters() {
    local dev serial driver
    for dev in /dev/ttyACM*; do
        [[ -e "$dev" ]] || continue
        serial=$(udevadm info -q property -n "$dev" 2>/dev/null | sed -n 's/^ID_SERIAL_SHORT=//p' | head -n 1)
        [[ -n "$serial" ]] && printf 'Leader candidate: %s  serial=%s\n' "$dev" "$serial"
    done
    for dev in /sys/class/net/can*; do
        [[ -e "$dev" ]] || continue
        driver=$(udevadm info -q property -p "$dev" 2>/dev/null | sed -n 's/^ID_NET_DRIVER=//p' | head -n 1)
        [[ "$driver" == gs_usb ]] || continue
        serial=$(udevadm info -q property -p "$dev" 2>/dev/null | sed -n 's/^ID_SERIAL_SHORT=//p' | head -n 1)
        [[ -n "$serial" ]] && printf 'CAN candidate: %s  serial=%s\n' "${dev##*/}" "$serial"
    done
}

if [[ "${1:-}" == --list ]]; then
    list_adapters
    exit 0
fi
if [[ $# -ne 0 ]]; then
    echo 'Usage: bash scripts/setup_ports.sh [--list]' >&2
    exit 2
fi

: "${LEADER_LEFT_SERIAL:?Set LEADER_LEFT_SERIAL from --list}"
: "${CAN_LEFT_SERIAL:?Set CAN_LEFT_SERIAL from --list}"
leader_right=${LEADER_RIGHT_SERIAL:-}
can_right=${CAN_RIGHT_SERIAL:-}
if [[ -n "$leader_right" && -z "$can_right" || -z "$leader_right" && -n "$can_right" ]]; then
    echo 'For dual arm, set both LEADER_RIGHT_SERIAL and CAN_RIGHT_SERIAL.' >&2
    exit 2
fi
for serial in "$LEADER_LEFT_SERIAL" "$CAN_LEFT_SERIAL" "$leader_right" "$can_right"; do
    [[ -z "$serial" || "$serial" =~ ^[A-Za-z0-9._-]+$ ]] || {
        echo "Invalid adapter serial: $serial" >&2
        exit 2
    }
done
if [[ "$LEADER_LEFT_SERIAL" == "$leader_right" && -n "$leader_right" || "$CAN_LEFT_SERIAL" == "$can_right" && -n "$can_right" ]]; then
    echo 'Left and right adapters must have distinct serials.' >&2
    exit 2
fi

leader_rules=$(mktemp)
left_link=$(mktemp)
right_link=$(mktemp)
trap 'rm -f "$leader_rules" "$left_link" "$right_link"' EXIT
cat > "$leader_rules" <<RULES
# Generated by open-a1z-teleop/scripts/setup_ports.sh
SUBSYSTEM=="tty", ATTRS{idVendor}=="1a86", ATTRS{idProduct}=="55d3", ATTRS{serial}=="$LEADER_LEFT_SERIAL", SYMLINK+="leader_left", GROUP="dialout", MODE="0660"
RULES
if [[ -n "$leader_right" ]]; then
    printf 'SUBSYSTEM=="tty", ATTRS{idVendor}=="1a86", ATTRS{idProduct}=="55d3", ATTRS{serial}=="%s", SYMLINK+="leader_right", GROUP="dialout", MODE="0660"\n' "$leader_right" >> "$leader_rules"
fi
cat > "$left_link" <<LINK
[Match]
Property=ID_SERIAL_SHORT=$CAN_LEFT_SERIAL
Driver=gs_usb
OriginalName=can*

[Link]
NamePolicy=
Name=can_left
LINK
if [[ -n "$can_right" ]]; then
    cat > "$right_link" <<LINK
[Match]
Property=ID_SERIAL_SHORT=$can_right
Driver=gs_usb
OriginalName=can*

[Link]
NamePolicy=
Name=can_right
LINK
fi

sudo install -m 0644 "$leader_rules" /etc/udev/rules.d/99-a1z-teleop-leader.rules
sudo install -m 0644 "$left_link" /etc/systemd/network/10-a1z-can-left.link
if [[ -n "$can_right" ]]; then
    sudo install -m 0644 "$right_link" /etc/systemd/network/11-a1z-can-right.link
fi
sudo udevadm control --reload-rules
echo 'Rules installed. Replug the adapters or reboot, then verify /dev/leader_left and can_left (and right-side names for dual arm).'
